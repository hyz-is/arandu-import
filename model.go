// runsTable is the table the runs live in.
const runsTable = "import_runs"

const (
	maxIdentifierLen = 64
	maxNameLen       = 160
	maxKeyLen        = 255
	maxFailureLen    = 255
)

// The two kinds of run.
const (
	// KindImport reads a file and writes its rows.
	KindImport = "import"
	// KindExport reads the application's records and writes a file.
	KindExport = "export"
)

// Status is where a run is. An import is Uploaded until somebody confirms it;
// an export starts Queued.
type Status string

const (
	// StatusUploaded is a file that was read and checked and waits for the
	// person to look at the preview and confirm.
	StatusUploaded Status = "uploaded"
	// StatusQueued is work waiting for the worker.
	StatusQueued Status = "queued"
	// StatusRunning is work the worker is doing.
	StatusRunning Status = "running"
	// StatusDone is work that ended; an import may still have refused rows.
	StatusDone Status = "done"
	// StatusFailed is work that stopped on something that was not a row.
	StatusFailed Status = "failed"
	// StatusDiscarded is an upload nobody confirmed: the person threw it away,
	// or the clean did.
	StatusDiscarded Status = "discarded"
)

// Statuses lists them in the order a run goes through them.
var Statuses = []Status{StatusUploaded, StatusQueued, StatusRunning, StatusDone, StatusFailed, StatusDiscarded}

// Valid says s is one of them.
func (s Status) Valid() bool {
	for _, known := range Statuses {
		if s == known {
			return true
		}
	}
	return false
}

// Active says the worker is, or will be, working on the run: the screen keeps
// asking how far along it is.
func (s Status) Active() bool { return s == StatusQueued || s == StatusRunning }

// The formats of a file.
const (
	FormatCSV  = "csv"
	FormatXLSX = "xlsx"
)

// Run is one import or export: the file, the state of the work and what it did.
//
// It embeds the model, so a row returned by a query carries the connection and
// can be saved again. Build a new one with Runs(db).New().
//
// A run keeps counts and never the content of a row: the rows are in the file,
// which the clean deletes, and in the application's own tables.
type Run struct {
	model.Model

	// ID is the identifier, generated by the application.
	ID string `db:"id"`
	// TenantID is the space the run belongs to, written from the Grant.
	TenantID string `db:"tenant_id"`
	// Definition is the key of the Definition.
	Definition string `db:"definition"`
	// Kind is KindImport or KindExport.
	Kind string `db:"kind"`
	// Status is where the run is.
	Status string `db:"status"`
	// Format is the format of the file: of the upload, or of the export.
	Format string `db:"format"`
	// FileName is what the person called the upload, or what the export is
	// called when it downloads.
	FileName string `db:"file_name"`
	// FileKey is where the upload or the export is on the Disk, generated by the
	// server. Empty once the clean deleted it, or before an export wrote it.
	FileKey string `db:"file_key"`
	// FileSize is its size in bytes.
	FileSize int64 `db:"file_size"`
	// ReportKey is where the refused rows are, as a CSV; empty when none were.
	ReportKey string `db:"report_key"`
	// Total is the rows in the file, and Processed how many the job has read.
	Total     int64 `db:"total"`
	Processed int64 `db:"processed"`
	// Created, Updated and Unchanged say what writing the rows did, and Refused
	// how many were turned away.
	Created   int64 `db:"created"`
	Updated   int64 `db:"updated"`
	Unchanged int64 `db:"unchanged"`
	Refused   int64 `db:"refused"`
	// Preview is what the screen shows before the confirmation, as JSON.
	Preview string `db:"preview"`
	// Sample is the first refused rows, as JSON, so the screen needs no file.
	Sample string `db:"sample"`
	// Failure is why a run failed, in a sentence the person can read.
	Failure string `db:"failure"`
	// ActorID is who started the run.
	ActorID string `db:"actor_id"`
	// CreatedAt and UpdatedAt are in UTC.
	CreatedAt time.Time `db:"created_at"`
	UpdatedAt time.Time `db:"updated_at"`
	// StartedAt and FinishedAt are when the worker began and ended.
	StartedAt  *time.Time `db:"started_at"`
	FinishedAt *time.Time `db:"finished_at"`
	// ExpiresAt is when the clean deletes the files of the run.
	ExpiresAt time.Time `db:"expires_at"`
}

// runTable declares the table once: its name, the ManualKey that says the text
// primary key is written by the application, and the default tenant_id scope.
// Runs is generated from it into RunQuery.go by aru model:build.
var runTable = model.NewTable(model.TableSpec{
	Name:      runsTable,
	New:       func() model.Entity { return new(Run) },
	ManualKey: true,
})

// arandu:begin custom

// Current is the status as a Status.
func (r Run) Current() Status { return Status(r.Status) }

// IsImport and IsExport say which kind of run it is.
func (r Run) IsImport() bool { return r.Kind == KindImport }
func (r Run) IsExport() bool { return r.Kind == KindExport }

// CanConfirm says the run is an upload waiting for the person's yes.
func (r Run) CanConfirm() bool { return r.IsImport() && r.Current() == StatusUploaded }

// CanDiscard says the same: only an upload nobody confirmed can be thrown away.
func (r Run) CanDiscard() bool { return r.CanConfirm() }

// Finished says the work ended, well or not.
func (r Run) Finished() bool { return r.Current() == StatusDone || r.Current() == StatusFailed }

// HasFile says the file the run produced or read is still on the Disk.
func (r Run) HasFile() bool { return r.FileKey != "" }

// HasReport says the refused rows are still on the Disk.
func (r Run) HasReport() bool { return r.ReportKey != "" }

// Percent is how far along the job is, from 0 to 100.
func (r Run) Percent() int {
	if r.Finished() {
		return 100
	}
	if r.Total <= 0 {
		return 0
	}
	p := int(r.Processed * 100 / r.Total)
	if p > 100 {
		p = 100
	}
	return p
}

// arandu:end custom

// ErrNotFound is returned when no row matches, including when the row exists in
// another tenant. The two cases are deliberately indistinguishable.
//
// It wraps model.ErrModelNotFound, so the router answers it with 404.
var ErrNotFound = fmt.Errorf("imports: run not found: %w", model.ErrModelNotFound)

// Line is one row of a file as the preview and the report tell it.
type Line struct {
	// Number is the row's place in the file, as the person's spreadsheet
	// numbers it.
	Number int `json:"number"`
	// Values are the cells by column key; Reason is why the row was refused, and
	// empty for a row that was fine.
	Values Row    `json:"values,omitempty"`
	Reason string `json:"reason,omitempty"`
}

// MappedColumn says which heading of the file became which column.
type MappedColumn struct {
	Key      string `json:"key"`
	Label    string `json:"label"`
	Heading  string `json:"heading,omitempty"`
	Required bool   `json:"required,omitempty"`
}

// Preview is what the screen shows before the confirmation.
type Preview struct {
	// Header says the first row of the file was a heading.
	Header bool `json:"header"`
	// Columns are the columns of the definition and what the file calls each.
	Columns []MappedColumn `json:"columns"`
	// Ignored are the headings of the file no column answers to.
	Ignored []string `json:"ignored,omitempty"`
	// Total is the rows read, Valid those that passed the check and Invalid
	// those that did not.
	Total   int `json:"total"`
	Valid   int `json:"valid"`
	Invalid int `json:"invalid"`
	// Sample is the first rows, and Problems the first rows refused.
	Sample   []Line `json:"sample,omitempty"`
	Problems []Line `json:"problems,omitempty"`
}

func decodePreview(raw string) Preview {
	var p Preview
	if raw != "" {
		_ = json.Unmarshal([]byte(raw), &p)
	}
	return p
}

func decodeLines(raw string) []Line {
	var lines []Line
	if raw != "" {
		_ = json.Unmarshal([]byte(raw), &lines)
	}
	return lines
}

// Resource is the list of fields one Run is allowed to answer with. A declared
// list rather than the entity itself: an encoder handed the entity answers with
// whatever it happens to have, and TenantID and the keys of the files are what
// belong in no response.
type Resource struct {
	run Run
}

// NewResource snapshots a run for a response.
func NewResource(r Run) Resource { return Resource{run: r} }

// ToArray returns the fields that may leave, by name.
func (r Resource) ToArray() map[string]any {
	run := r.run
	out := map[string]any{
		"id": run.ID, "definition": run.Definition, "kind": run.Kind, "status": run.Status,
		"format": run.Format, "file_name": run.FileName, "total": run.Total, "processed": run.Processed,
		"percent": run.Percent(), "created": run.Created, "updated": run.Updated, "unchanged": run.Unchanged,
		"refused": run.Refused, "failure": run.Failure,
		"created_at": run.CreatedAt.UTC().Format(time.RFC3339),
		"expires_at": run.ExpiresAt.UTC().Format(time.RFC3339),
		"has_file":   run.HasFile(), "has_report": run.HasReport(),
	}
	if run.FinishedAt != nil {
		out["finished_at"] = run.FinishedAt.UTC().Format(time.RFC3339)
	}
	if run.IsImport() && run.Current() == StatusUploaded {
		out["preview"] = decodePreview(run.Preview)
	}
	if run.Refused > 0 {
		out["problems"] = decodeLines(run.Sample)
	}
	return out
}

// With returns what goes beside the fields: nothing does.
func (r Resource) With() map[string]any { return nil }
